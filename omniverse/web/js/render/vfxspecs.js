// What every ability looks like. SPEC_BY_FX sets the look of each effect family; SPEC_BY_ABILITY
// overrides it for abilities that share a family but should look different (bigger, darker,
// another colour, another shape).
//
// kind: orb | lightning | beam | flame | vortex | thrown | slash | shock | giant | combo | trap | aura | shield
// Common fields: c1 body colour, c2 inner colour, glow, size (scale), plus per-renderer options.

const orb = (c1, c2, glow, o = {}) => ({ kind: 'orb', c1, c2, glow, spiral: 0, ...o });
const darkOrb = (c1, rim, glow, o = {}) => ({ kind: 'orb', dark: true, c1, c2: rim, rim, glow, ...o });
const bolt = (c1, glow, o = {}) => ({ kind: 'lightning', c1, glow, ...o });
const beam = (c1, c2, glow, o = {}) => ({ kind: 'beam', c1, c2, glow, ...o });
const flame = (c1, c2, glow, o = {}) => ({ kind: 'flame', c1, c2, glow, boom: 'boom', ...o });
const thrown = (shape, o = {}) => ({ kind: 'thrown', shape, glow: '#ffffff', ...o });
const slash = (c1, c2, o = {}) => ({ kind: 'slash', c1, c2, ...o });
const shock = (style, c1, o = {}) => ({ kind: 'shock', style, c1, glow: c1, ...o });
const giant = (style, o = {}) => ({ kind: 'giant', style, ...o });
const aura = (c1, c2, o = {}) => ({ kind: 'aura', c1, c2, glow: c1, ...o });
const shield = (style, c1, o = {}) => ({ kind: 'shield', style, c1, ...o });
const warp = (style, c1, o = {}) => ({ kind: 'warp', warp: style, c1, ...o });

